"""Generates gwent/src/DuelVectors.as from gwent/tests/vectors.json for the in-game self-test.

usage:
  vectors.py [--vectors <vectors.json>] [--out <DuelVectors.as>]

Each vector becomes one row of a static array, one row per line, written as a JSON value (an
AS3 array or string literal has the same syntax for these values). Numbers are plain integer
literals, which AS3 keeps exact up to 2^53, so uint values never pass through lossy arithmetic.

Row shapes:
  RANDOM           [seed, game, stream, n, v1..v8]   n = 0: nextUint draws, else nextInt(stream, n)
  HASH             [expected, word1, word2, ...]     words are signed int32 values
  CODEC            [token, version, matchId, seq, type, argsCsv, hash]
  CODEC_MALFORMED  token                             must decode to null
  WINDOW           [scenarioIndex, name, matchId, ingest, popsCsv, gap]   one row per step
"""
import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

GWENT_DIR = Path(__file__).resolve().parent.parent
DEFAULT_VECTORS = GWENT_DIR / "tests" / "vectors.json"
DEFAULT_OUT = GWENT_DIR / "src" / "DuelVectors.as"

ROW_INDENT = " " * 12

HEADER = """package red.game.witcher3.menus.gwint
{
   /**
    * Test vectors from gwent/tests/vectors.json (the Python reference gwent/tools/duelref.py), replayed by
    * DuelSelfTest. Generated by gwent/build/vectors.py: do not edit, regenerate.
    * Each array is built when its getter is called, so a normal match never allocates them.
    */
   public class DuelVectors
   {
"""

FOOTER = """   }
}
"""

DOCS = {
    "RANDOM": "Rows [seed, game, stream, n, v1..v8]: n = 0 means eight nextUint draws, else eight nextInt(stream, n).",
    "HASH": "Rows [expected, word1, word2, ...]: the DuelHash value after addInt of every word.",
    "CODEC": "Rows [token, version, matchId, seq, type, argsCsv, hash]: decode and encode must agree both ways.",
    "CODEC_MALFORMED": "Tokens that DuelCodec.decode must reject (null).",
    "WINDOW": "Rows [scenarioIndex, name, matchId, ingest, popsCsv, gap]: one window step; a new index starts "
              "a fresh DuelWindow.",
}


def rows(data: dict[str, Any]) -> dict[str, list[Any]]:
    """Flattens the vectors into the rows of each generated array, keyed by array name."""
    random_rows = [row[:3] + [0] + row[3:] for row in data["random"]["uint"]] + list(data["random"]["int"])
    hash_rows = [[expected] + list(words)
                 for expected, words in zip(data["hash"]["expected"], data["hash"]["words"], strict=True)]
    window_rows = []
    for index, scenario in enumerate(data["window"]):
        steps = zip(scenario["ingest"], scenario["pops"], scenario["gap"], strict=True)
        for ingest, pops, gap in steps:
            window_rows.append([index, scenario["name"], scenario["matchId"], ingest, pops, gap])
    return {
        "RANDOM": random_rows,
        "HASH": hash_rows,
        "CODEC": list(data["codec"]["valid"]),
        "CODEC_MALFORMED": list(data["codec"]["malformed"]),
        "WINDOW": window_rows,
    }


def _literal(value: Any) -> str:
    """One row as an AS3 literal; rejects anything AS3 would not keep exact."""
    if isinstance(value, bool) or isinstance(value, float):
        raise ValueError(f"vector value {value!r} is not an integer or a string")
    if isinstance(value, int) and not -2**31 <= value <= 2**32 - 1:
        raise ValueError(f"vector value {value} is outside the int and uint range")
    if isinstance(value, list):
        return "[" + ",".join(_literal(item) for item in value) + "]"
    return json.dumps(value, ensure_ascii=True)


def render(data: dict[str, Any]) -> str:
    """The DuelVectors.as source for the vectors in data (LF line endings)."""
    parts = [HEADER]
    for index, (name, values) in enumerate(rows(data).items()):
        if index:
            parts.append("\n")
        body = ",\n".join(ROW_INDENT + _literal(value) for value in values)
        parts.append(f"      /** {DOCS[name]} */\n"
                     f"      public static function get {name}() : Array\n"
                     f"      {{\n"
                     f"         return [\n{body}\n         ];\n"
                     f"      }}\n")
    parts.append(FOOTER)
    return "".join(parts)


def write(vectors_path: Path, out: Path) -> None:
    """Reads vectors_path and writes the generated class to out as ASCII with LF endings."""
    data = json.loads(vectors_path.read_text(encoding="ascii"))
    out.write_bytes(render(data).encode("ascii"))


def main(argv: Sequence[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--vectors", type=Path, default=DEFAULT_VECTORS)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    write(args.vectors, args.out)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
